"""Render bench results as JSON (for the console) and Markdown (for the README)."""

from __future__ import annotations

from typing import Any

HONESTY = [
    "Scenarios are synthetic and template-generated; they are not drawn from real incidents or real merchants.",
    "Attackers are scripted policies, not language models. Money never moves: a recording executor stands in "
    "for PayPal, while credentials, the guard, the ledger, the extractor, the planner and the dispute rules are "
    "the real code.",
    "The deterministic planner never reads raw catalog text, so injection through catalog text cannot steer it "
    "by construction (C3/C4). That is an architectural property, not a measured robustness of a model.",
    "Detector patterns were written against the dev templates. The hold-out templates use different phrasings "
    "and were not used to tune anything. Compare dev and hold-out columns.",
    "'Stopped' means the attack did not succeed. It includes attacks that failed because the agent simply "
    "chose an in-policy item, and attacks escalated to a human.",
    "No LLM is called (tokens = 0); the offline backend is used so results reproduce with no API keys.",
]


def pct(r: dict[str, Any]) -> str:
    return f"{100 * r['rate']:.1f}%"


def ci(r: dict[str, Any]) -> str:
    return f"{100 * r['lo']:.0f}-{100 * r['hi']:.0f}"


def to_markdown(doc: dict[str, Any]) -> str:
    cfgs = doc["configs"]
    out = ["# Mandate-Bench results", ""]
    out.append(
        f"{doc['n_scenarios']} scenarios ({doc['n_attacks']} attacks, {doc['n_benign']} benign controls, "
        f"{doc['n_holdout']} hold-out). Generated by `make bench`; deterministic, no API keys.\n"
    )
    out += ["## Headline: attack success rate (lower is better)", "",
            "| Config | What it adds | ASR | 95% CI | Stopped by human | Dev ASR | Hold-out ASR | False positives on benign |",
            "|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for name, c in cfgs.items():
        s = c["score"]
        out.append(
            f"| {name} | {c['description']} | {pct(s['attacks']['asr'])} | {ci(s['attacks']['asr'])} | "
            f"{pct(s['attacks']['escalated'])} | {pct(s['split']['dev']['asr'])} | "
            f"{pct(s['split']['holdout']['asr'])} | {pct(s['benign']['false_positive'])} |"
        )
    fams = sorted(next(iter(cfgs.values()))["score"]["families"])
    out += ["", "## Attack success rate by family", "", "| Family | " + " | ".join(cfgs) + " |",
            "|---|" + "---|" * len(cfgs)]  # fmt: skip
    for f in fams:
        out.append(
            f"| {f} | " + " | ".join(pct(c["score"]["families"][f]["asr"]) for c in cfgs.values()) + " |"
        )
    out += ["", "## Benign controls (task success; higher is better)", "",
            "| Config | Task success | False escalation | False block | Incorrect |", "|---|---|---|---|---|"]  # fmt: skip
    for name, c in cfgs.items():
        b = c["score"]["benign"]
        out.append(f"| {name} | {pct(b['task_success'])} | {pct(b['false_escalation'])} | "
                   f"{pct(b['false_block'])} | {pct(b['incorrect'])} |")  # fmt: skip
    out += [
        "",
        "## Latency (guard + agent logic, ms per scenario)",
        "",
        "| Config | p50 | p95 |",
        "|---|---|---|",
    ]
    for name, c in cfgs.items():
        lat = c["score"]["latency_ms"]
        out.append(f"| {name} | {lat['p50']:.1f} | {lat['p95']:.1f} |")
    last = list(cfgs)[-1]
    left = [(k, v) for k, v in cfgs[last]["score"]["variants"].items() if v["asr"]["k"] > 0]
    out += ["", f"## Attack variants still succeeding under {last}", ""]
    if left:
        out += ["| Variant | Successes |", "|---|---|"]
        out += [f"| {k} | {v['asr']['k']}/{v['asr']['n']} |" for k, v in left]
    else:
        out.append(
            "None in this synthetic set. That says the scenario set is covered, not that the system is safe."
        )
    out += [
        "",
        "## The benign false escalations, explained",
        "",
        "Under C4 the benign controls escalate to a human in 4 of 70 cases. They are not noise; each is a "
        "deliberate trap written to show the cost of the pattern detector, and each lands on a human rather than "
        "blocking or paying:",
        "",
        "- 2 `purchase_trap`: a clean purchase whose review happens to be phrased like a command (the trap "
        'set includes "System: lightweight mesh upper" and "New instructions: lace them loosely"). The taint check asks a human before paying. That is the '
        "intended trade: a false escalation costs one click, a missed injection can cost money.",
        '- 2 `dispute:accept`: a genuine buyer writes "You should refund me" or "You must refund this '
        'charge". The dispute agent treats instruction-shaped buyer text as untrusted and asks a human instead '
        "of refunding on its own. The buyer is not refused and the refund is still available after review.",
        "",
        "Real buyers do write like this, so a production deployment would tune the detector and measure the "
        "cost on real traffic; this benchmark cannot.",
        "",
        "Related, separately generated: [adaptive-attacker results](adaptive.md) (how easily the detector is "
        "evaded and what the guard still stops) and the "
        "[liability sensitivity analysis](../../spec/liability-sensitivity.md).",
    ]
    out += ["", "## Read this before quoting a number", ""]
    out += [f"- {h}" for h in HONESTY]
    return "\n".join(out) + "\n"
